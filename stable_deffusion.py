def generate_images(pipe, prompts, save_dir):

    generated = []

    for i, prompt in enumerate(prompts):

        generator = torch.Generator(
            device="cuda"
        ).manual_seed(1000 + i)

        with torch.inference_mode():

            image = pipe(
                prompt,
                height=512,
                width=512,
                num_inference_steps=25,
                guidance_scale=7.0,
                generator=generator
            ).images[0]

        image.save(f"{save_dir}/{i:03d}.png")
        generated.append(image)

        print(f"Generated {i+1}/{len(prompts)}")

    return generated


