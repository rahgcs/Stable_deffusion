import random
from collections import defaultdict, Counter

TOTAL_IMAGES = 1500
TRAIN_COUNT = 1400
VAL_COUNT = 100

random.seed(42)

# Group dataset indices by product category.
category_indices = defaultdict(list)

for idx, text in enumerate(dataset["text"]):
    category = text.split(",", 1)[0].strip().lower()
    category_indices[category].append(idx)

print("Categories:")
for category, indices in category_indices.items():
    print(category, len(indices))

# Shuffle each category.
for category in category_indices:
    random.shuffle(category_indices[category])

# Round-robin sampling gives each category representation.
selected_indices = []

while len(selected_indices) < TOTAL_IMAGES:
    added = False

    for category in sorted(category_indices):
        if category_indices[category]:
            selected_indices.append(
                category_indices[category].pop()
            )
            added = True

            if len(selected_indices) == TOTAL_IMAGES:
                break

    if not added:
        break

random.shuffle(selected_indices)

selected_dataset = dataset.select(selected_indices)

print("Selected:", len(selected_dataset))

def prepare_caption(original_caption):

    parts = original_caption.split(",", 2)

    if len(parts) == 3:
        category = parts[0].strip()
        visual_description = parts[2].strip()

        caption = (
            f"{category} fashion product, "
            f"{visual_description}"
        )
    else:
        caption = original_caption.strip()

    return caption


